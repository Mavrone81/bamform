/**
 * Reference QR matrices produced by an INDEPENDENT implementation:
 * `qrcode@1.5.4` ("node-qrcode", MIT), error-correction level M, byte mode
 * FORCED (`create([{data, mode: 'byte'}], ...)`).
 *
 * The forcing matters. Left to itself node-qrcode splits a mixed string into
 * several segments and encodes the uppercase base32 run of an `otpauth://`
 * URI in the denser alphanumeric mode. Both symbols scan to the identical
 * string, but they are different matrices, so a fixture taken from the
 * optimised path would compare our byte-mode encoder against a different
 * encoding rather than against a different implementation. Our encoder is
 * byte-mode-only on purpose (see `qrcode.ts`): one mode, ~90 fewer lines,
 * and at most one version larger for our payloads.
 *
 * WHY THESE EXIST. `src/lib/qrcode.ts` is hand-rolled — the repo takes on no
 * new runtime dependency (slice 13-UI-A report, dependency assessment) — so
 * nothing inside this codebase can independently say whether its output is a
 * VALID QR symbol. "Our encoder agrees with our test" is not evidence. Every
 * module below was emitted by a different, widely-deployed encoder that was
 * never installed into this repository: it was run once in a scratch
 * directory outside the worktree and only its output was copied here.
 *
 * WHY node-qrcode AND NOT qrcode-generator. Both were run. They disagree on
 * 8 of these 11 payloads — not on the data, but on which of the eight data
 * MASKS to choose, because `qrcode-generator` scores masks with a
 * home-grown adjacency heuristic instead of ISO/IEC 18004 §8.8.2's four
 * penalty rules. Any of the eight masks yields a scannable symbol (the
 * format information records which one), so neither is "wrong" — but only
 * node-qrcode implements the published rules, so it is the one worth
 * matching. `AUTO_MASK_CASES` therefore pins our mask SELECTION as well as
 * our encoding, and `FIXED_MASK_CASE` pins all eight mask formulas
 * independently of selection.
 *
 * Regenerate (only if the encoder's contract deliberately changes):
 *
 *   mkdir /tmp/qrref && cd /tmp/qrref && npm init -y && npm i qrcode@1.5.4
 *   node -e "const q=require('qrcode').create([{data:TEXT,mode:'byte'}],{errorCorrectionLevel:'M'});
 *            console.log(q.maskPattern);
 *            for(let r=0;r<q.modules.size;r++){let s='';
 *            for(let c=0;c<q.modules.size;c++)s+=q.modules.get(r,c)?'1':'0';console.log(s)}"
 *
 * A row is one scan line, '1' = dark. No quiet zone (the renderer adds it).
 */

